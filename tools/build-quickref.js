// Builds the Quick Reference from js/data/private/quickref-source.html (the wording, private repo only):
//   js/data/private/quickref.js                            shown in the app's Quick reference tab (private build)
//   js/data/private/Rogue-Warriors-Quick-Reference-A4.pdf  two A4 pages, printed double-sided (flip on the long edge)
// Styling is css/quickref.css, shared by the app and the PDF. Needs Playwright:  NODE_PATH=/opt/npm-tools/node_modules node tools/build-quickref.js
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'js', 'data', 'private');
const source = fs.readFileSync(path.join(DIR, 'quickref-source.html'), 'utf8');

fs.writeFileSync(path.join(DIR, 'quickref.js'), '/* Generated by tools/build-quickref.js from quickref-source.html. Private build only. */\nwindow.RW_QUICKREF = { html: ' + JSON.stringify(source) + ' };\n');

const url = (rel) => 'file://' + path.join(ROOT, rel);
const fonts = [['League Gothic', 400, 'league-gothic-latin-400-normal'], ['Oswald', 400, 'oswald-latin-400-normal'], ['Oswald', 600, 'oswald-latin-600-normal'],
  ['PT Sans Narrow', 400, 'pt-sans-narrow-latin-400-normal'], ['PT Sans Narrow', 700, 'pt-sans-narrow-latin-700-normal']]
  .map(([f, w, file]) => `@font-face{font-family:'${f}';font-weight:${w};src:url('${url('assets/fonts/' + file + '.woff2')}')}`).join('\n');
const html = `<!doctype html><html lang="en-CA"><head><meta charset="utf-8"><title>Rogue Warriors Quick Reference</title>
<style>${fonts}
@page{size:A4;margin:0}
*{margin:0;padding:0}
html,body{background:#fff;-webkit-print-color-adjust:exact;print-color-adjust:exact}</style>
<link rel="stylesheet" href="${url('css/quickref.css')}"></head><body><div class="qr print">${source}</div></body></html>`;
const tmp = path.join(require('os').tmpdir(), 'rw-quickref.html');
fs.writeFileSync(tmp, html);

(async () => {
  const { chromium } = require('playwright');
  const b = await chromium.launch({ args: ['--allow-file-access-from-files'] });
  const p = await b.newPage();
  await p.goto('file://' + tmp);
  await p.evaluate(() => document.fonts.ready);
  const fit = await p.evaluate(() => [...document.querySelectorAll('.page')].map((pg) => {
    const r = pg.getBoundingClientRect();
    let over = 0;
    pg.querySelectorAll('*').forEach((el) => { const e = el.getBoundingClientRect(); if (e.height && e.bottom > r.bottom - 8) over = Math.max(over, Math.round(e.bottom - (r.bottom - 8))); });
    return { id: pg.id, over, clipped: pg.scrollHeight > pg.clientHeight + 1 };
  }));
  console.log('fit', JSON.stringify(fit));
  if (fit.some((f) => f.over > 0 || f.clipped)) { console.error('build-quickref: a page overflows A4. Trim text or reduce sizes.'); await b.close(); process.exit(1); }
  await p.pdf({ path: path.join(DIR, 'Rogue-Warriors-Quick-Reference-A4.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true });
  await b.close();
  console.log('built quickref.js and the A4 PDF');
})();
