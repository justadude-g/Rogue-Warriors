def R(x1, y1, x2, y2):
    return f"M{x1} {y1}H{x2}V{y2}H{x1}Z"

def P(*pts):
    return "M" + "L".join(f"{x} {y}" for x, y in pts) + "Z"

def C(cx, cy, r):
    return f"M{cx-r} {cy}a{r} {r} 0 1 0 {2*r} 0a{r} {r} 0 1 0 {-2*r} 0Z"

def RR(x1, y1, x2, y2, r):
    return (f"M{x1+r} {y1}H{x2-r}Q{x2} {y1} {x2} {y1+r}V{y2-r}Q{x2} {y2} {x2-r} {y2}"
            f"H{x1+r}Q{x1} {y2} {x1} {y2-r}V{y1+r}Q{x1} {y1} {x1+r} {y1}Z")

